// Chart library v2 (owner approval 2026-11-09, docs/chart-library-proposal.md): chart TYPES (the visual form, the
// main grouping of the picker), each with named VARIANTS (a ChartType plus options, one click). Function and style
// are filters across types; small multiples, top N, sort, log scale and per-capita / index / y/y transforms are
// modifiers of every type, not variants. One palette for every style: a style changes notation, never colours.

import type { ChartType, ZOptions } from "./types";

export const CHART_STYLES = ["standard", "business", "scientific", "editorial"] as const;
export type ChartStyle = (typeof CHART_STYLES)[number];

/** What a chart answers (FT Visual Vocabulary). */
export const CHART_FUNCTIONS = [
  "time",
  "magnitude",
  "rank",
  "part",
  "distribution",
  "correlation",
  "deviation",
  "spatial",
  "flow",
] as const;
export type ChartFunction = (typeof CHART_FUNCTIONS)[number];

/** Groups of types in the picker. */
export const PICKER_GROUPS = ["compare", "time", "part", "distribution", "relation", "maps", "tables"] as const;
export type PickerGroup = (typeof PICKER_GROUPS)[number];

/** What a variant needs from the data beyond measures and dimensions (a variant without it is not available). */
export type VariantNeed =
  | "uncertainty"
  | "projection"
  | "flows"
  | "target"
  | "categories"
  | "hierarchy"
  | "voivodeships"
  | "two-periods"
  | "previous-year"
  | "three-measures";

export type ChartVariant = {
  /** "type.variant", stable: used in URLs, saved views and dashboard YAML. */
  id: string;
  type: TypeId;
  pl: string;
  en: string;
  chart: ChartType;
  opts?: ZOptions;
  functions: ChartFunction[];
  styles: ChartStyle[];
  needs?: VariantNeed[];
  /** Data transform applied by the caller before drawing. */
  transform?: "index" | "share";
  usePl: string;
  useEn: string;
};

export type TypeId =
  | "line"
  | "column"
  | "bar"
  | "area"
  | "combo"
  | "scatter"
  | "bubble"
  | "dot"
  | "dumbbell"
  | "slope"
  | "bump"
  | "pyramid"
  | "histogram"
  | "boxplot"
  | "strip"
  | "fan"
  | "waterfall"
  | "bullet"
  | "pie"
  | "treemap"
  | "waffle"
  | "heatmap"
  | "choropleth"
  | "symbols"
  | "tiles"
  | "sankey"
  | "table"
  | "matrix"
  | "kpi"
  | "sparkline";

export type ChartTypeDef = { id: TypeId; pl: string; en: string; group: PickerGroup; core: boolean; variants: ChartVariant[] };

type V = Omit<ChartVariant, "id" | "type"> & { key: string };
const T = (id: TypeId, pl: string, en: string, group: PickerGroup, core: boolean, vs: V[]): ChartTypeDef => ({
  id,
  pl,
  en,
  group,
  core,
  variants: vs.map(({ key, ...v }) => ({ ...v, id: `${id}.${key}`, type: id })),
});
